def main():
    ts_path = Path(__file__).with_name("ImmersiveLoudness_en.ts")
    text = ts_path.read_text(encoding="utf-8")

    # Replace each unfinished translation with the English text
    # Pattern: <source>XXX</source>...<translation type="unfinished"></translation>
    def repl(m):
        src = m.group(1)
        eng = TRANS.get(src, src)  # fallback to source if not found
        eng_escaped = xml_esc.escape(eng)
        return f'<source>{src}</source>\n        <translation>{eng_escaped}</translation>'

    # Replace both empty unfinished translations and fallback Chinese translations
    new_text = re.sub(
        r'<source>(.*?)</source>\s*<translation[^>]*>.*?</translation>',
        repl,
        text,
        flags=re.DOTALL,
    )

    ts_path.write_text(new_text, encoding="utf-8")
    print(f"Updated {ts_path}")

if __name__ == "__main__":
    main()
